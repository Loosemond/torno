"""Writes the offline API reference of the build123d the kernel pins, for torno's `build123d` skill.

    cd kernel && uv run --no-sync python scripts/build123d_api.py          # writes the file
    cd kernel && uv run --no-sync python scripts/build123d_api.py --check  # exits 1 if the file is stale

The file is `app/resources/agent-plugin/skills/build123d/reference/api-<version>.txt`: every name `build123d` exports
(`__all__`) and the base classes of those that are not, with its signature and the first line of its docstring,
grouped by the module that defines it. A class
lists the members it defines itself, so a method is found under the class it comes from. The agent greps it. The
text depends on the installed build123d alone; `tests/test_skill_api.py` holds the file to it.
"""

from __future__ import annotations

import enum
import inspect
import re
import sys
from pathlib import Path

import build123d

REFERENCE_DIR = Path(__file__).parents[2] / "app" / "resources" / "agent-plugin" / "skills" / "build123d" / "reference"

SUMMARY = 150


def reference_path() -> Path:
    return REFERENCE_DIR / f"api-{build123d.__version__}.txt"


def render() -> str:
    """The reference of the installed build123d: the same text each time it is made from the same install."""
    by_module: dict[str, list[str]] = {}
    exported = {name: getattr(build123d, name) for name in build123d.__all__}
    # The bases a class has that are not exported (Shape, Mixin1D, Mixin3D...) carry most of what a shape does.
    for obj in list(exported.values()):
        for base in obj.__mro__[1:] if inspect.isclass(obj) else ():
            if base.__module__.startswith("build123d") and base.__name__ not in exported:
                exported[base.__name__] = base
    for name in sorted(exported, key=str.lower):
        obj = exported[name]
        module = getattr(obj, "__module__", None)
        if not isinstance(module, str) or not module.startswith("build123d") or isinstance(obj, (int, float, str, dict)):
            module = "constants"
        by_module.setdefault(module, []).append(_entry(name, obj))
    lines = [
        f"build123d {build123d.__version__}: every name `from build123d import *` gives, with its signature and the first line of",
        "its docstring, by the module that defines it. A class lists the members it defines itself: a Solid's own, and those",
        "of its bases (Shape, Mixin1D, Mixin2D, Mixin3D, listed too) under the base. Generated by kernel/scripts/build123d_api.py:",
        "do not edit; grep it (`Fillet`, `^def fillet`, `Mixin3D.max_fillet`).",
        "",
    ]
    for module in sorted(by_module, key=lambda m: (m == "constants", m)):
        lines += [f"## {module}", "", *by_module[module]]
    return "\n".join(lines).rstrip() + "\n"


def _entry(name: str, obj: object) -> str:
    if inspect.isclass(obj):
        return _class(name, obj)
    if callable(obj):
        return f"def {name}{_sig(obj)}{_summary(obj)}\n"
    return f"{name} = {_value(obj)}\n"


def _class(name: str, cls: type) -> str:
    bases = [b.__name__ for b in cls.__bases__ if b is not object]
    head = f"class {name}({', '.join(bases)})" if bases else f"class {name}"
    out = [f"{head}{_summary(cls)}"]
    if issubclass(cls, enum.Enum):
        out.append("  members: " + ", ".join(m.name for m in cls))
    else:
        out.append(f"  {name}{_sig(cls)}")
    members = [(n, v) for n, v in vars(cls).items() if not n.startswith("_")]
    meta = type(cls)
    if meta is not type and not issubclass(cls, enum.Enum):
        # Axis.X, Plane.XY: the class's own names live on its metaclass.
        members += [(n, v) for n, v in vars(meta).items() if not n.startswith("_") and isinstance(v, property)]
    for member, value in members:
        if isinstance(value, enum.Enum):
            continue
        out.append(_member(name, member, value))
    return "\n".join(out) + "\n"


def _member(cls: str, name: str, value: object) -> str:
    if isinstance(value, (staticmethod, classmethod)):
        kind = "static " if isinstance(value, staticmethod) else "class "
        func = value.__func__
        return f"  {kind}{cls}.{name}{_sig(func, drop_first=isinstance(value, classmethod))}{_summary(func)}"
    if isinstance(value, property):
        return f"  property {cls}.{name}{_summary(value.fget or value)}"
    if inspect.isfunction(value):
        return f"  {cls}.{name}{_sig(value, drop_first=True)}{_summary(value)}"
    if callable(value):
        return f"  {cls}.{name}{_summary(value)}"
    return f"  {cls}.{name} = {_value(value)}"


def _sig(obj: object, drop_first: bool = False) -> str:
    try:
        sig = inspect.signature(obj)
        if inspect.isclass(obj) and list(sig.parameters) == ["args", "kwargs"]:
            # The objects' metaclass takes anything and hands it on; the signature is __init__'s.
            sig, drop_first = inspect.signature(obj.__init__), True
    except (TypeError, ValueError):
        return "(...)"
    params = list(sig.parameters.values())
    if drop_first and params and params[0].name in ("self", "cls"):
        params = params[1:]
    text = str(sig.replace(parameters=params))
    # Whatever a default prints with an address is not the same text twice.
    text = re.sub(r" at 0x[0-9a-f]+", "", text)
    # Annotations that are not strings print with their module path; the name says enough.
    return re.sub(r"\b(?:build123d|collections\.abc|typing)(?:\.[a-z_0-9]+)*\.(?=[A-Za-z])", "", text)


def _summary(obj: object) -> str:
    doc = inspect.cleandoc(getattr(obj, "__doc__", None) or "")
    first = next((line.strip() for line in doc.splitlines() if line.strip()), "")
    if len(first) > SUMMARY:
        first = first[: SUMMARY - 1].rstrip() + "…"
    return f": {first}" if first else ""


def _value(value: object) -> str:
    # A set prints in the order its hashes fall, which is not the same twice.
    text = "{" + ", ".join(sorted(repr(v) for v in value)) + "}" if isinstance(value, (set, frozenset)) else repr(value)
    return text if len(text) <= 80 else text[:79] + "…"


def main(argv: list[str]) -> int:
    path, text = reference_path(), render()
    if "--check" in argv:
        fresh = path.is_file() and path.read_text() == text
        print(f"{path}: {'up to date' if fresh else 'stale or missing'}")
        return 0 if fresh else 1
    path.parent.mkdir(parents=True, exist_ok=True)
    for old in path.parent.glob("api-*.txt"):
        if old != path:
            old.unlink()
    path.write_text(text)
    print(f"wrote {path} ({len(text.encode()):,} bytes, {text.count(chr(10)):,} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
